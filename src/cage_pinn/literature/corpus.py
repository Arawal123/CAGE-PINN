def _paper(**values: Any) -> dict[str, Any]:
    defaults: dict[str, Any] = {
        "date": "",
        "venue": "",
        "doi": "",
        "external_identifier": "",
        "peer_review_status": "not verified",
        "source_urls": "",
        "full_text_access_status": "abstract/metadata checked",
        "problem_class": "multiple",
        "method_family": "",
        "exact_methodological_change": "",
        "controller_signal": "none identified",
        "adapted_object": "",
        "reference_solution_required_during_training": "no",
        "compute_overhead": "not extracted",
        "architecture_dependence": "not extracted",
        "supported_pde_types": "not extracted",
        "assumptions": "not extracted",
        "central_claim": "",
        "reported_advantages": "not extracted",
        "reported_disadvantages": "not extracted",
        "limitations_stated_by_authors": "not extracted",
        "limitations_inferred_by_us": "Requires independent full-text audit before claim use.",
        "benchmarks": "not extracted",
        "seed_count": "not extracted",
        "comparator_quality": "not audited",
        "compute_fairness_quality": "not audited",
        "ablation_quality": "not audited",
        "code_url": "",
        "code_license": "not verified",
        "relation_to_cage": "",
        "collision_severity": 3,
        "supporting_pointer": "abstract/metadata unless otherwise stated",
        "extraction_status": "screened; full extraction incomplete",
    }
    defaults.update(values)
    missing = {"canonical_title", "authors", "year"} - defaults.keys()
    if missing:
        raise ValueError(f"Missing required paper fields: {missing}")
    return {field: defaults.get(field, "") for field in SCHEMA}


