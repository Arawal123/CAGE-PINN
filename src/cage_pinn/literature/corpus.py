def _normalized_title(value: str) -> str:
    return re.sub(r"[^a-z0-9]+", "", value.lower())


def _dedup_key(row: pd.Series) -> str:
    doi = str(row.get("doi", "")).strip().lower()
    identifier = str(row.get("external_identifier", "")).strip().lower()
    if doi:
        return f"doi:{doi}"
    if identifier:
        return f"id:{identifier}"
    return f"title:{_normalized_title(str(row['canonical_title']))}:{int(row['year'])}"


def build_corpus(directory: str | Path = "research/literature") -> dict[str, Any]:
    target = Path(directory)
    target.mkdir(parents=True, exist_ok=True)
    frame = pd.DataFrame(seed_records(), columns=SCHEMA)
    frame["_dedup_key"] = frame.apply(_dedup_key, axis=1)
    duplicates = frame[frame.duplicated("_dedup_key", keep=False)]
    if not duplicates.empty:
        titles = duplicates["canonical_title"].tolist()
        raise ValueError(f"Literature corpus contains duplicate identities: {titles}")
    frame = frame.drop(columns=["_dedup_key"]).sort_values(
        ["year", "canonical_title"], kind="stable"
    )
    csv_path = target / "papers.csv"
    parquet_path = target / "papers.parquet"
    frame.to_csv(csv_path, index=False)
    frame.to_parquet(parquet_path, index=False)
    digest = hashlib.sha256(csv_path.read_bytes()).hexdigest()
    return {
        "records": len(frame),
        "csv": str(csv_path),
        "parquet": str(parquet_path),
        "sha256": digest,
        "status": "seed corpus; systematic expansion and independent full-text review pending",
    }

